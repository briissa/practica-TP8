CREATE TABLE IF NOT EXISTS experiment_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visitor_id TEXT NOT NULL,
  variant TEXT NOT NULL CHECK (variant IN ('a', 'b')),
  event_type TEXT NOT NULL CHECK (event_type IN ('impression', 'conversion')),
  session_id TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (event_type <> 'impression' OR session_id IS NOT NULL),
  CHECK (event_type <> 'conversion' OR session_id IS NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS experiment_one_impression_per_session
  ON experiment_events (visitor_id, session_id)
  WHERE event_type = 'impression';

CREATE UNIQUE INDEX IF NOT EXISTS experiment_one_conversion_per_visitor
  ON experiment_events (visitor_id)
  WHERE event_type = 'conversion';
